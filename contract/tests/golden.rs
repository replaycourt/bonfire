const PARAMS: &str = include_str!("../../sim/params.json");

fn launch_config(block: &str) -> Config {
    let v: Value = serde_json::from_str(PARAMS).unwrap();
    serde_json::from_value(v[block]["config"].clone()).expect("sim/params.json matches Config")
}

fn account(name: &str) -> near_sdk::AccountId {
    acc(&format!("{name}.testnet"))
}

fn outcome(word: &str) -> Outcome {
    match word {
        "LIT" => Outcome::Lit,
        "SMOKED" => Outcome::Smoked,
        _ => Outcome::Cold,
    }
}

fn play(founders: &[(&str, u128)], accounts: &[&str], script: &[Step], nights: &[Night]) {
    let config = launch_config("simulation");
    let night_ms = config.night_ms;
    let f = founders.iter().map(|&(n, a)| Founder { account_id: account(n), amount: U128(a) }).collect();
    let mut g = Game::with(config, f);
    let all: Vec<_> = accounts.iter().map(|a| account(a)).collect();
    let start = |n: u32| START_MS + (n as u64 - 1) * night_ms;
    for want in nights {
        let n = want.night;
        for s in script.iter().filter(|s| s.night == n) {
            let t = start(n) + s.at_ms;
            assert!(t >= g.now_ms);
            g.now_ms = t;
            let (who, other) = (account(s.who), account(s.other_or_self()));
            match s.kind {
                "throw" => {
                    g.throw(&who, s.amount);
                }
                "kindle" => {
                    g.kindle(&who);
                }
                "transfer" => g.transfer(&who, &other, s.amount),
                k => panic!("unknown step {k}"),
            }
        }
        g.now_ms = start(n + 1);
        assert_eq!(g.settle().settled, 1);
        let got = g.night_view(n).unwrap();
        assert_eq!(got.outcome, outcome(want.outcome), "night {n}");
        assert_eq!(
            (got.target.0, got.pile.0, got.minted.0, got.burned.0, got.supply.unwrap().0),
            (want.target, want.pile, want.minted, want.burned, want.supply),
            "night {n}: target, pile, minted, burned, supply"
        );
        assert_eq!((got.target_next.unwrap().0, got.streak), (want.next_target, want.streak), "night {n}");
        g.collect_all(&all);
        assert_eq!(g.state().hearth.0, want.hearth, "night {n}: hearth after everyone collected");
        for (a, &b) in all.iter().zip(want.balances) {
            assert_eq!(g.balance(a), b, "night {n}: balance of {a}");
            assert_eq!(g.holder(a).pending.0, 0);
        }
        g.assert_conserved(&all);
    }
    g.assert_events_match();
}

impl Step {
    fn other_or_self(&self) -> &'static str {
        if self.other.is_empty() { self.who } else { self.other }
    }
}

#[test]
fn the_contract_settles_the_pooling_scenario_exactly_like_the_model() {
    play(POOLING_FOUNDERS, POOLING_ACCOUNTS, POOLING_SCRIPT, POOLING_NIGHTS);
    assert!(POOLING_NIGHTS.iter().any(|n| n.dust > 0), "the scenario exercises rounding dust");
}

#[test]
fn the_contract_settles_the_capped_scenario_exactly_like_the_model() {
    play(CAP_FOUNDERS, CAP_ACCOUNTS, CAP_SCRIPT, CAP_NIGHTS);
    // Night 1's target is capped: 20,000 * 1.07 = 21,400 would exceed a quarter of the free supply.
    assert!(CAP_NIGHTS[0].next_target < CAP_NIGHTS[0].target * 107 / 100);
}

#[test]
fn both_launch_blocks_of_sim_params_json_are_accepted_at_init() {
    for block in ["simulation", "testnet"] {
        let c = launch_config(block);
        let f = (0..5).map(|i| Founder { account_id: founder(i), amount: U128(10u128.pow(22)) }).collect();
        let g = Game::with(c.clone(), f);
        let mut g = g;
        assert_eq!(g.view(|x| x.config()).config, c, "{block}");
    }
}
